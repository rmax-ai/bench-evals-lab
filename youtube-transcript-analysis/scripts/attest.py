#!/usr/bin/env python3
"""Record a human attestation over the ground truth of one results directory.

Attestations are appended to verification/attestation.json (re-attesting with
the same verifier name replaces that entry). The claims worksheet
(verification/claims.md) is generated by verify_package.py.

Usage:
    uv run python scripts/attest.py --verifier "Max" --status verified \\
        --method full --notes "reviewed all claims against transcript + video"
    uv run python scripts/attest.py --verifier "Max" --status contested \\
        --method spot --contested C007:"38% on slide, not 36%" \\
        --resolved C007:"accepted as-is after checking video @ 08:58"
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

EVAL_DIR = Path(__file__).resolve().parents[1]
CONFIG_PATH = EVAL_DIR / "config.json"


def parse_pairs(raw: list[str] | None) -> dict[str, str]:
    """Parse 'ID:text' pairs into a dict."""
    pairs: dict[str, str] = {}
    for item in raw or []:
        if ":" not in item:
            raise ValueError(f"expected ID:text, got {item!r}")
        claim_id, text = item.split(":", 1)
        pairs[claim_id.strip()] = text.strip()
    return pairs


def find_results_dir(config: dict, slug: str) -> Path | None:
    candidates = sorted((EVAL_DIR / "results").glob(f"*-{slug}"), reverse=True)
    return candidates[0] if candidates else None


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verifier", required=True, help="Name of the human attesting")
    parser.add_argument("--status", required=True, choices=["verified", "contested"],
                        help="verified = all checked claims pass; contested = issues recorded")
    parser.add_argument("--method", choices=["full", "spot"], default="spot",
                        help="full = every claim checked; spot = triage subset checked")
    parser.add_argument("--notes", default="", help="Free-form verification notes")
    parser.add_argument("--contested", action="append", metavar="ID:NOTE",
                        help="Claim ID and the problem found (repeatable)")
    parser.add_argument("--resolved", action="append", metavar="ID:NOTE",
                        help="Contested claim ID and its resolution (repeatable)")
    parser.add_argument("--results-dir", type=Path, default=None,
                        help="Results directory (default: newest for the first configured video)")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    config = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    video = config["videos"][0]
    results_dir = args.results_dir or find_results_dir(config, video["slug"])
    if results_dir is None:
        print("error: no results directory for the configured video", file=sys.stderr)
        return 2
    attestation_path = results_dir / "verification" / "attestation.json"
    if not attestation_path.exists():
        print("error: run scripts/verify_package.py first to create the attestation file",
              file=sys.stderr)
        return 2
    try:
        contested = parse_pairs(args.contested)
        resolved = parse_pairs(args.resolved)
        document = json.loads(attestation_path.read_text(encoding="utf-8"))
        entry = {
            "verifier": args.verifier,
            "date": datetime.now(timezone.utc).isoformat(),
            "method": args.method,
            "status": args.status,
            "notes": args.notes,
            "contested": [{"claim_id": k, "note": v} for k, v in contested.items()],
            "resolved": [{"claim_id": k, "note": v} for k, v in resolved.items()],
        }
        attestations = document.setdefault("attestations", [])
        attestations = [a for a in attestations if a.get("verifier") != args.verifier]
        attestations.append(entry)
        document["attestations"] = attestations
        attestation_path.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    print(f"attested: {args.verifier} [{args.status}] ({args.method})")
    if contested:
        print(f"  contested: {', '.join(contested)}")
    print(f"  -> {attestation_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
